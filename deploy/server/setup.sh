#!/usr/bin/env bash
# Sets up (or updates) one MotoFlow server: Amazon Linux 2023 on EC2, x86_64. Guide: docs/CICD.md
#
# Run as root, either:
#   - paste the whole file into "User data" when launching the instance, or
#   - AWS Console -> Systems Manager -> Run Command -> AWS-RunShellScript -> paste it -> pick the instance.
# Running it again updates compose.yaml, Caddyfile and the scripts in /opt/motoflow/bin.
# It never overwrites /opt/motoflow/.env (settings and secrets) once that file exists.
set -euo pipefail

# ---- Used only when /opt/motoflow/.env is created the first time --------------------------
# Domain of this environment, e.g. dev.motoflow.example.com: Caddy then gets a free HTTPS
# certificate by itself (the domain's DNS A record must point to this server's Elastic IP).
# ":80" = plain HTTP on the public IP, only for a first test (the refresh cookie needs HTTPS).
SITE_ADDRESS=":80"
# "true"  = PostgreSQL in a container on this server.
# "false" = Amazon RDS: afterwards set DB_URL, DB_USERNAME and DB_PASSWORD in /opt/motoflow/.env.
LOCAL_DB="true"
# --------------------------------------------------------------------------------------------

APP_DIR=/opt/motoflow

echo "== Docker, Docker Compose, SSM agent"
dnf install -y docker
systemctl enable --now docker
if ! docker compose version >/dev/null 2>&1; then
  mkdir -p /usr/local/lib/docker/cli-plugins
  curl -fsSL "https://github.com/docker/compose/releases/latest/download/docker-compose-linux-$(uname -m)" \
    -o /usr/local/lib/docker/cli-plugins/docker-compose
  chmod 755 /usr/local/lib/docker/cli-plugins/docker-compose
fi
docker compose version
command -v aws >/dev/null || dnf install -y awscli-2
systemctl enable --now amazon-ssm-agent || true

echo "== Swap (JVM + PostgreSQL on a small instance)"
if [ ! -f /swapfile ]; then
  dd if=/dev/zero of=/swapfile bs=1M count=2048 status=none
  chmod 600 /swapfile
  mkswap /swapfile
  swapon /swapfile
  echo '/swapfile none swap defaults 0 0' >> /etc/fstab
fi

mkdir -p "$APP_DIR/bin"
cd "$APP_DIR"

echo "== compose.yaml"
cat > compose.yaml <<'EOF'
# Generated by deploy/server/setup.sh (MotoFlow_BE). Change setup.sh, not this file.
name: motoflow

x-logging: &logging
  driver: json-file
  options: { max-size: "10m", max-file: "3" }

services:
  # Public entry point: HTTPS (automatic when SITE_ADDRESS is a domain); /api/* -> backend, rest -> frontend.
  proxy:
    image: caddy:2-alpine
    restart: unless-stopped
    ports: ["80:80", "443:443", "443:443/udp"]
    environment:
      SITE_ADDRESS: ${SITE_ADDRESS:-:80}
    volumes:
      - ./Caddyfile:/etc/caddy/Caddyfile:ro
      - caddy-data:/data
      - caddy-config:/config
    logging: *logging

  # Image written to images.env by bin/deploy-service (MotoFlow_FE pipeline).
  frontend:
    image: ${FRONTEND_IMAGE:-motoflow-frontend:not-deployed-yet}
    restart: unless-stopped
    logging: *logging

  # Image written to images.env by bin/deploy-service (MotoFlow_BE pipeline).
  backend:
    image: ${BACKEND_IMAGE:-motoflow-backend:not-deployed-yet}
    restart: unless-stopped
    ports: ["127.0.0.1:8080:8080"] # host only, for the health check in bin/deploy-service
    stop_grace_period: 30s
    mem_limit: ${BACKEND_MEM_LIMIT:-1g}
    depends_on:
      db: { condition: service_healthy, required: false }
    environment:
      SPRING_PROFILES_ACTIVE: ${SPRING_PROFILES_ACTIVE:-prod}
      # Trust X-Forwarded-Proto from Caddy, so https requests are not seen as cross-origin.
      SERVER_FORWARD_HEADERS_STRATEGY: native
      DB_URL: ${DB_URL:-jdbc:postgresql://db:5432/motoflow}
      DB_USERNAME: ${DB_USERNAME:-motoflow}
      DB_PASSWORD: ${DB_PASSWORD:?DB_PASSWORD is missing in /opt/motoflow/.env}
      MOTOFLOW_JWT_SECRET: ${MOTOFLOW_JWT_SECRET:?MOTOFLOW_JWT_SECRET is missing in /opt/motoflow/.env}
      MOTOFLOW_CORS_ORIGINS: ${MOTOFLOW_CORS_ORIGINS:-http://localhost}
      MOTOFLOW_ADMIN_USERNAME: ${MOTOFLOW_ADMIN_USERNAME:-admin}
      MOTOFLOW_ADMIN_PASSWORD: ${MOTOFLOW_ADMIN_PASSWORD:-}
      MOTOFLOW_AUTH_REFRESHCOOKIE_SECURE: ${REFRESH_COOKIE_SECURE:-true}
    logging: *logging

  # Starts only with COMPOSE_PROFILES=local-db in .env; with RDS it never runs.
  db:
    image: postgres:17
    profiles: [local-db]
    restart: unless-stopped
    environment:
      POSTGRES_DB: motoflow
      POSTGRES_USER: ${DB_USERNAME:-motoflow}
      POSTGRES_PASSWORD: ${DB_PASSWORD:?DB_PASSWORD is missing in /opt/motoflow/.env}
    volumes:
      - pg-data:/var/lib/postgresql/data
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U $$POSTGRES_USER -d motoflow"]
      interval: 5s
      timeout: 3s
      retries: 30
    logging: *logging

volumes:
  caddy-data:
  caddy-config:
  pg-data:
EOF

echo "== Caddyfile"
cat > Caddyfile <<'EOF'
# Generated by deploy/server/setup.sh (MotoFlow_BE). Change setup.sh, not this file.
{$SITE_ADDRESS} {
	encode zstd gzip

	# Backend REST API (the code uses /api/..., not /api/v1).
	handle /api/* {
		reverse_proxy backend:8080
	}

	# Everything else is the React app.
	handle {
		reverse_proxy frontend:80
	}
}
EOF

echo "== bin/motoflow"
cat > bin/motoflow <<'EOF'
#!/usr/bin/env bash
# docker compose for the MotoFlow stack. Examples:
#   sudo /opt/motoflow/bin/motoflow ps
#   sudo /opt/motoflow/bin/motoflow logs -f --tail 200 backend
#   sudo /opt/motoflow/bin/motoflow up -d backend     (after editing .env)
set -euo pipefail
cd /opt/motoflow
exec docker compose --env-file .env --env-file images.env "$@"
EOF

echo "== bin/deploy-service"
cat > bin/deploy-service <<'EOF'
#!/usr/bin/env bash
# deploy-service <backend|frontend> <account.dkr.ecr.region.amazonaws.com/repo@sha256:...>
# Called by GitHub Actions through SSM (.github/scripts/ssm-deploy.sh), as root.
# Pulls the image and restarts the service, then waits until it is healthy. If it is not,
# it puts the previous image back and fails, so the pipeline turns red while the site keeps working.
set -euo pipefail

SERVICE="${1:?service}"
IMAGE="${2:?image}"
APP_DIR=/opt/motoflow
MF="$APP_DIR/bin/motoflow"
cd "$APP_DIR"

case "$SERVICE" in
  backend) VAR=BACKEND_IMAGE ;;
  frontend) VAR=FRONTEND_IMAGE ;;
  *) echo "Unknown service: $SERVICE" >&2; exit 2 ;;
esac
case "$IMAGE" in
  *.dkr.ecr.*.amazonaws.com/*@sha256:*) ;;
  *) echo "Expected an ECR image by digest, got: $IMAGE" >&2; exit 2 ;;
esac

# The backend and frontend pipelines may deploy at the same time: one at a time on this server.
exec 9>"$APP_DIR/.deploy.lock"
flock -w 900 9

touch images.env
set_image() {
  grep -v "^$VAR=" images.env > images.env.tmp || true
  echo "$VAR=$1" >> images.env.tmp
  mv images.env.tmp images.env
}

# Backend: Spring Boot Actuator answers {"status":"UP"} once the application started (Flyway
# included) and PostgreSQL answers, and 503 {"status":"DOWN"} otherwise.
healthy() {
  local body
  for _ in $(seq 1 60); do # up to 3 minutes
    if [ "$SERVICE" = backend ]; then
      body="$(curl -fsS --max-time 5 http://127.0.0.1:8080/actuator/health)" \
        && [[ "$body" == *'"status":"UP"'* ]] && return 0
    else
      "$MF" exec -T frontend wget -q -O /dev/null http://127.0.0.1/ 2>/dev/null && return 0
    fi
    sleep 3
  done
  return 1
}

REGISTRY="${IMAGE%%/*}"
REGION="$(echo "$REGISTRY" | cut -d. -f4)"
aws ecr get-login-password --region "$REGION" | docker login --username AWS --password-stdin "$REGISTRY" >/dev/null

PREVIOUS="$(grep "^$VAR=" images.env | cut -d= -f2- || true)"
echo "Deploying $SERVICE: $IMAGE"
echo "Previous: ${PREVIOUS:-none}"

set_image "$IMAGE"
"$MF" pull "$SERVICE"
"$MF" up -d "$SERVICE"

if healthy; then
  echo "$SERVICE is healthy."
  docker image prune -f >/dev/null || true
  exit 0
fi

echo "$SERVICE did not become healthy. Last log lines:" >&2
"$MF" logs --tail 100 "$SERVICE" >&2 || true
if [ -n "$PREVIOUS" ] && [ "$PREVIOUS" != "$IMAGE" ]; then
  echo "Rolling back $SERVICE to $PREVIOUS" >&2
  set_image "$PREVIOUS"
  "$MF" up -d "$SERVICE" || true
fi
exit 1
EOF
chmod 755 bin/motoflow bin/deploy-service

echo "== .env"
if [ ! -f .env ]; then
  secret() { head -c 32 /dev/urandom | base64 | tr -d '\n'; }
  alnum() { head -c 96 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | cut -c1-"$1"; }
  case "$SITE_ADDRESS" in
    :*|http://*) SECURE=false; ORIGIN=http://localhost ;;
    *) SECURE=true; ORIGIN="https://$SITE_ADDRESS" ;;
  esac
  PROFILES=""
  if [ "$LOCAL_DB" = true ]; then PROFILES=local-db; fi
  umask 077
  cat > .env <<EOF
# MotoFlow server settings and secrets (root only). After editing:
#   sudo /opt/motoflow/bin/motoflow up -d proxy backend
SITE_ADDRESS=$SITE_ADDRESS
COMPOSE_PROFILES=$PROFILES
SPRING_PROFILES_ACTIVE=prod
DB_URL=jdbc:postgresql://db:5432/motoflow
DB_USERNAME=motoflow
DB_PASSWORD=$(alnum 32)
MOTOFLOW_JWT_SECRET=$(secret)
MOTOFLOW_CORS_ORIGINS=$ORIGIN
# First Admin: created only while the database has no Admin; the password must be changed at first sign-in.
MOTOFLOW_ADMIN_USERNAME=admin
MOTOFLOW_ADMIN_PASSWORD=$(alnum 16)
# false only while SITE_ADDRESS is plain HTTP; browsers drop Secure cookies over http.
REFRESH_COOKIE_SECURE=$SECURE
BACKEND_MEM_LIMIT=1g
EOF
  umask 022
  echo "Created .env with new random secrets."
else
  echo ".env already exists, left unchanged."
fi
chmod 600 .env
touch images.env

echo "== Start proxy (and database)"
bin/motoflow up -d --force-recreate proxy
if grep -q '^COMPOSE_PROFILES=.*local-db' .env; then
  bin/motoflow up -d db
fi
bin/motoflow ps

echo "Done. First Admin password: sudo grep MOTOFLOW_ADMIN_PASSWORD /opt/motoflow/.env"
